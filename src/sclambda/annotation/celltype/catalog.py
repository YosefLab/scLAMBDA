"""
Cell-type catalog (Stage A for cell typing).

Once per run, enumerate the canonical cell types that can occur in this
``{organism} {tissue}`` — the universe of candidate labels. Seeding the
dossier's candidate pool from this catalog means rare-but-real cell types are
*considered* (not just the obvious ones), and gives every cluster a shared,
consistent label space. Generated by one LLM call and cached for the run;
degrades gracefully to an empty catalog (data-only generation) on failure.
"""

from __future__ import annotations

import json
import logging
import os
import re
from dataclasses import dataclass, field

logger = logging.getLogger(__name__)

PROMPT_DIR = os.path.join(os.path.dirname(__file__), "prompts")


@dataclass
class CatalogCellType:
    cell_type: str
    prior: str = "medium"                       # very high / high / medium / low / very low
    lineage: str = ""                           # parent lineage (e.g. "lymphoid")
    markers: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "cell_type": self.cell_type,
            "prior": self.prior,
            "lineage": self.lineage,
            "markers": self.markers,
        }

    @classmethod
    def from_dict(cls, d: dict) -> "CatalogCellType | None":
        name = str(d.get("cell_type", "")).strip()
        if not name:
            return None
        return cls(
            cell_type=name,
            prior=str(d.get("prior", "medium")).strip().lower() or "medium",
            lineage=str(d.get("lineage", "")).strip(),
            markers=[str(x).strip() for x in d.get("markers", []) if str(x).strip()],
        )


@dataclass
class CellTypeCatalog:
    organism: str
    tissue: str
    entries: list[CatalogCellType] = field(default_factory=list)

    def to_dicts(self) -> list[dict]:
        return [e.to_dict() for e in self.entries]

    def to_markdown(self) -> str:
        if not self.entries:
            return "(no catalog available)"
        lines = [
            f"### Cell-type catalog — canonical cell types of {self.organism} {self.tissue}",
            "",
            "| Cell type | Prior | Lineage | Marker genes |",
            "|---|---|---|---|",
        ]
        for e in self.entries:
            lines.append(
                f"| {e.cell_type} | {e.prior} | {e.lineage or '—'} | {', '.join(e.markers) or '—'} |"
            )
        return "\n".join(lines)


def _parse_catalog(text: str) -> list[CatalogCellType]:
    match = re.search(r"\[.*\]", text or "", re.DOTALL)
    if not match:
        return []
    try:
        data = json.loads(match.group())
    except json.JSONDecodeError as e:
        logger.warning("Failed to parse cell-type catalog JSON: %s", e)
        return []
    if not isinstance(data, list):
        return []
    out = []
    for d in data:
        if isinstance(d, dict):
            e = CatalogCellType.from_dict(d)
            if e is not None:
                out.append(e)
    return out
